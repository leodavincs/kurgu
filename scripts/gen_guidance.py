#!/usr/bin/env python3
"""Generate every copy of the agent guidance from guidance/ (the single source).

    python scripts/gen_guidance.py            # rewrite the generated files
    python scripts/gen_guidance.py --check    # exit 1 if any generated file is out of date (CI)

Writes guidance_gen.py (AGENT_BLOCK, WAKE_PROMPT, MCP tool descriptions: imported at run time, so the installed wheel needs no data files) and the
`<!-- kurgu:generated:NAME -->` ... `<!-- kurgu:generated:end -->` regions of SKILL.md, AGENTS.md, README.md, README.tr.md and SPEC.md. Text outside
the markers is hand-written and never touched. Stdlib only; reads nothing outside this repository."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "guidance")
REF = re.compile(r"\{\{([\w/\-]+)#([\w\-]+)\}\}")

# (file, region name, template under guidance/targets/, indent)
REGIONS = [
    ("skills/kurgu/SKILL.md", "rules", "region.rules-full", ""),
    ("AGENTS.md", "rules", "region.rules-full", "   "),
    ("AGENTS.md", "commands", "region.commands", ""),
    ("README.md", "agent-side", "region.readme", ""),
    ("README.tr.md", "agent-side", "region.readme-tr", ""),
    ("README.md", "tool-names", "region.tool-names", ""),
    ("README.tr.md", "tool-names", "region.tool-names", ""),
    ("SPEC.md", "tool-names", "region.tool-names", ""),
]
TOOLS = ["render_frame", "render_strip", "rerender", "detect", "notes_list", "notes_wait", "notes_done", "notes_ask"]       # guidance/tools/<name>.md


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8", newline="") as f:
        return f.read()


_cache = {}


def sections(name):
    """{variant: text} of guidance/<name>.md (sections start with a line `@@ variant`)."""
    if name not in _cache:
        out, cur = {}, None
        for line in read(f"guidance/{name}.md").split("\n"):
            if line.startswith("@@ "):
                cur = line[3:].strip()
                out[cur] = []
            elif cur is not None:
                out[cur].append(line)
        _cache[name] = {k: "\n".join(v).strip("\n") for k, v in out.items()}
    return _cache[name]


def render(text, trail=()):
    def sub(m):
        name, var = m.group(1), m.group(2)
        if (name, var) in trail:
            raise SystemExit(f"gen_guidance: reference loop at {name}#{var}")
        try:
            body = sections(name)[var]
        except (OSError, KeyError):
            raise SystemExit(f"gen_guidance: no section {name}#{var} in guidance/{name}.md")
        return render(body, trail + ((name, var),))
    return REF.sub(sub, text)


def template(name):
    return render(read(f"guidance/targets/{name}.md").strip("\n"))


def py_str(name, text, wrap):
    if not wrap:
        return f"{name} = {text!r}\n"
    lines = text.split("\n")
    parts = [repr(l + "\n") for l in lines[:-1]] + [repr(lines[-1])] if lines[-1] else [repr(l + "\n") for l in lines[:-1]]
    return f"{name} = (\n" + "\n".join("    " + p for p in parts) + "\n)\n"


def guidance_module():
    block = template("agent_block") + "\n"
    wake = " ".join(template("wake").split())
    out = ['"""GENERATED by scripts/gen_guidance.py from guidance/. Do not edit; change guidance/ and rerun the script."""\n\n',
           py_str("AGENT_BLOCK", block, True), "\n",
           py_str("WAKE_PROMPT", wake, False), "\n", "TOOL_DESCRIPTIONS = {\n"]
    for t in TOOLS:
        out.append(f"    {t!r}: {render(sections('tools/' + t)['description'])!r},\n")
    out.append("}\n\n")
    out.append("# `kurgu --help` command table, in display order\nCOMMAND_HELP = {\n")
    for line in sections("commands")["help"].split("\n"):
        name, desc = line.split(" :: ", 1)
        out.append(f"    {name!r}: {desc!r},\n")
    out.append("}\n\n# `kurgu help <topic>`: plain-text topics from guidance/topics/<topic>.md\nHELP_TOPICS = {\n")
    tdir = os.path.join(SRC, "topics")
    for fn in sorted(os.listdir(tdir)) if os.path.isdir(tdir) else []:
        if fn.endswith(".md"):
            out.append(f"    {fn[:-3]!r}: {read('guidance/topics/' + fn).strip() + chr(10)!r},\n")
    out.append("}\n")
    return "".join(out)


def region_re(name):
    return re.compile(r"(<!-- kurgu:generated:%s -->\n)(.*?)(<!-- kurgu:generated:end -->)" % re.escape(name), re.S)


def apply_regions(rel, text):
    for f, name, tpl, indent in REGIONS:
        if f != rel:
            continue
        m = region_re(name).search(text)
        if not m:
            raise SystemExit(f"gen_guidance: {rel} has no `<!-- kurgu:generated:{name} -->` ... `<!-- kurgu:generated:end -->` markers")
        body = "\n".join((indent + l) if l.strip() else l for l in template(tpl).split("\n")) + "\n" + indent
        text = text[:m.start(2)] + body + text[m.start(3):]
    return text


def generate():
    """{relative path: new content} for every generated file."""
    out = {"guidance_gen.py": guidance_module()}
    for rel in sorted({r[0] for r in REGIONS}):
        out[rel] = apply_regions(rel, read(rel))
    return out


def main(argv=None):
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for rel, new in generate().items():
        try:
            old = read(rel)
        except OSError:
            old = None
        if old != new:
            stale.append(rel)
            if not check:
                with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="") as f:
                    f.write(new)
    if check and stale:
        print("Out of date: " + ", ".join(stale) + "\nrun scripts/gen_guidance.py", file=sys.stderr)
        return 1
    print(("up to date" if not stale else "wrote " + ", ".join(stale)) if not check else "up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
